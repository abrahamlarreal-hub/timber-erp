#!/usr/bin/env bash
# Concatenates migrations + seed into one file for the Supabase SQL Editor.
set -euo pipefail
cd "$(dirname "$0")/.."
out=setup/01_full_setup.sql
{
  echo "-- Timpanogos Timber Co. ERP — complete database setup (schema + logic + seed data)"
  echo "-- Generated by scripts/build-setup-sql.sh. Paste into Supabase SQL Editor and Run."
  for f in supabase/migrations/*.sql; do echo; echo "-- >>> $f"; cat "$f"; done
  echo; echo "-- >>> supabase/seed.sql"; cat supabase/seed.sql
} > "$out"
echo "wrote $out ($(wc -c < "$out") bytes)"
